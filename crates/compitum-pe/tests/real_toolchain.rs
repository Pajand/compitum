//! Regression tests against binaries produced by a real compiler and linker.
//!
//! # Why this file exists
//!
//! Every other parser test uses a fixture built by this repository, and that is not enough.
//! **A fixture that shares an assumption with the code under test cannot detect that
//! assumption being wrong.**
//!
//! This is not hypothetical. The first version of the parser read the optional header at
//! offsets computed by chaining from `SectionAlignment`, and it was wrong. On a genuine
//! compiler-produced binary it read `Subsystem` as 4096 instead of 3 (console), and it read
//! the data-directory array from the middle of unrelated fields. The fixture builder chained
//! from the same anchor, so the writer and the reader agreed with each other while both
//! disagreed with reality. **325 tests passed and real binaries were classified
//! incorrectly.** Only third-party output exposed it.
//!
//! These tests are therefore the most valuable in the crate: they are the only ones that can
//! catch a shared assumption being wrong, because the bytes come from a toolchain that knows
//! nothing about this code.
//!
//! # The corpus
//!
//! `tests/corpus/` holds four files generated by `tools/make_corpus.py` from clang and
//! lld-link, each ~1 KiB, with a signed `manifest.json` recording their digests and the
//! toolchain that produced them. They are committed rather than generated in CI so that the
//! check runs even where no compiler is installed.
//!
//! Regenerate with:
//!
//! ```console
//! $ python3 tools/make_corpus.py
//! ```
//!
//! Routing decisions against the same corpus are tested in `compitum-router`, which is where
//! the router, the ISA oracle and the parser are all in scope.

use std::path::PathBuf;

use compitum_pe::{parse, PeImage};

/// The directory holding the corpus, relative to this crate.
fn corpus_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/corpus")
}

/// Reads one corpus file, failing with a useful message when it is missing.
fn corpus(name: &str) -> Vec<u8> {
    let path = corpus_dir().join(name);
    std::fs::read(&path).unwrap_or_else(|error| {
        panic!(
            "corpus file {} could not be read: {error}\n\
             Regenerate it with: python3 tools/make_corpus.py",
            path.display()
        )
    })
}

/// Parses one corpus file.
fn parse_corpus(name: &str) -> PeImage {
    let bytes = corpus(name);
    parse(&bytes).unwrap_or_else(|error| panic!("{name} failed to parse: {error}"))
}

/// The four fixtures the corpus is expected to hold.
const CORPUS_FILES: [&str; 4] = [
    "real-console-4k.exe",
    "real-gui-4k.exe",
    "real-console-16k.exe",
    "real-arm64ec.exe",
];

// ===========================================================================
// The regression this file was written for.
// ===========================================================================

/// The parser must read the optional header at the offsets the PE specification defines.
///
/// This is the exact defect the corpus was created to catch. The previous implementation
/// chained offsets from an anchor and had drifted eight bytes by the time it reached
/// `Subsystem`, so a console application with a real subsystem value of 3 was reported as
/// having an unrecognized subsystem, and a GUI application would have been reported as
/// headless-capable — a wrong answer in the dangerous direction, because it would route a
/// display-dependent program into a headless pipeline.
#[test]
fn real_console_binary_is_classified_as_a_console_application() {
    for name in ["real-console-4k.exe", "real-console-16k.exe"] {
        let image = parse_corpus(name);
        assert_eq!(
            image.subsystem().id(),
            "windows_console",
            "{name}: a real linker wrote IMAGE_SUBSYSTEM_WINDOWS_CUI (3) for this file"
        );
        assert!(
            image.is_headless_capable(),
            "{name}: a console application can run without a display"
        );
    }
}

/// A GUI binary must **not** be reported as headless-capable.
///
/// This is the dangerous direction of the same bug: telling an operator that a
/// display-dependent program will run in a headless pipeline, when it will fail.
#[test]
fn real_gui_binary_is_not_headless_capable() {
    let image = parse_corpus("real-gui-4k.exe");
    assert_eq!(
        image.subsystem().id(),
        "windows_gui",
        "a real linker wrote IMAGE_SUBSYSTEM_WINDOWS_GUI (2) for this file"
    );
    assert!(
        !image.is_headless_capable(),
        "a graphical application declared as headless-capable would be routed into a \
         pipeline where it cannot run"
    );
    assert!(image.subsystem().requires_display());
}

/// The data-directory array must be read from its real position.
///
/// The old anchor pointed eight bytes early, so every directory entry was read from the wrong
/// place. An import directory therefore appeared absent on a file that had one, and unrelated
/// header fields were read as directory entries.
#[test]
fn real_binaries_read_the_data_directory_from_the_right_place() {
    for name in CORPUS_FILES {
        let image = parse_corpus(name);
        let optional = image
            .optional
            .as_ref()
            .expect("a linked image has an optional header");

        // These four files are built with /nodefaultlib and no imports, so every directory
        // entry is genuinely zero. Any non-zero value here means the parser is reading
        // unrelated fields as directory entries -- which is exactly what it used to do.
        assert_eq!(
            optional.import_directory_rva, 0,
            "{name}: this image has no imports, so the parser must not invent one"
        );
        assert_eq!(
            optional.clr_header_rva, 0,
            "{name}: this is native code, not managed, so the CLR directory must be empty"
        );
        assert_eq!(
            optional.load_config_rva, 0,
            "{name}: no load configuration was emitted, so none must be reported"
        );
        assert!(
            !image.is_managed(),
            "{name}: reporting a native binary as managed would change its routing entirely"
        );
        assert!(
            !image.imports_graphics(),
            "{name}: no graphics module was linked, so none may be reported"
        );
    }
}

/// The image size and header size must come from their real fields.
#[test]
fn real_binaries_report_coherent_sizes() {
    for name in ["real-console-4k.exe", "real-console-16k.exe"] {
        let image = parse_corpus(name);
        let optional = image.optional.as_ref().expect("optional header present");

        // A real linker emits 512-byte headers for these small images, independent of the
        // section alignment. Asserting it pins the field position: if the parser were reading
        // the wrong offset, this would not land on 512.
        assert_eq!(
            optional.size_of_headers, 512,
            "{name}: a real linker emits 512-byte headers here"
        );
        assert!(
            optional.size_of_image >= optional.size_of_headers,
            "{name}: the image cannot be smaller than its own headers ({} < {})",
            optional.size_of_image,
            optional.size_of_headers
        );
        assert_eq!(
            optional.implied_page_size(),
            optional.section_alignment,
            "{name}: the implied page size is the section alignment"
        );
    }
}

/// The optional header's magic must be PE32+, which is what every ARM64 binary uses.
#[test]
fn real_arm64_binaries_use_the_pe32_plus_layout() {
    for name in [
        "real-console-4k.exe",
        "real-gui-4k.exe",
        "real-console-16k.exe",
    ] {
        let image = parse_corpus(name);
        let optional = image.optional.as_ref().expect("optional header present");

        assert_eq!(
            optional.magic,
            compitum_pe::parser::MAGIC_PE32_PLUS,
            "{name}: 64-bit images use the PE32+ optional header"
        );
        assert!(optional.is_pe32_plus());
        // A 64-bit image can be loaded above 4 GiB, which is why the field is 64 bits.
        assert!(
            optional.image_base > u64::from(u32::MAX),
            "{name}: a PE32+ image base should exceed the 32-bit range, and a value below it \
             would mean the 32-bit field was read instead"
        );
    }
}

