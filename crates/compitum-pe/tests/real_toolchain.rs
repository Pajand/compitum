/// The manifest's recorded values must match what the parser reports.
///
/// The manifest is produced by an independent reader in `tools/make_corpus.py` that knows
/// nothing about this crate, so agreeing with it is meaningful evidence rather than
/// self-consistency.
#[test]
fn parser_agrees_with_the_independent_manifest() {
    let path = corpus_dir().join("manifest.json");
    let text = std::fs::read_to_string(path).expect("manifest must exist");
    let manifest = compitum_json::parse(&text).expect("manifest must be valid JSON");
    let files = manifest["files"]
        .as_object()
        .expect("manifest has a files object");

    let mut checked = 0;
    for (name, entry) in files.iter() {
        let image = parse_corpus(name);

        assert_eq!(
            u64::from(image.coff.machine.raw()),
            entry["machine"].as_u64().unwrap_or(0),
            "{name}: machine type disagrees with the independent reading"
        );
        assert_eq!(
            u64::from(image.subsystem().0),
            entry["subsystem"].as_u64().unwrap_or(0),
            "{name}: subsystem disagrees with the independent reading"
        );

        let optional = image.optional.as_ref().expect("optional header present");
        assert_eq!(
            u64::from(optional.section_alignment),
            entry["section_alignment"].as_u64().unwrap_or(0),
            "{name}: section alignment disagrees"
        );
        assert_eq!(
            u64::from(optional.size_of_image),
            entry["size_of_image"].as_u64().unwrap_or(0),
            "{name}: image size disagrees"
        );
        assert_eq!(
            u64::from(optional.size_of_headers),
            entry["size_of_headers"].as_u64().unwrap_or(0),
            "{name}: header size disagrees"
        );
        assert_eq!(
            u64::from(optional.dll_characteristics),
            entry["dll_characteristics"].as_u64().unwrap_or(0),
            "{name}: DLL characteristics disagree"
        );
        assert_eq!(
            optional.import_directory_rva, 0,
            "{name}: no imports were linked, so none may be reported"
        );

        checked += 1;
    }

    assert_eq!(checked, CORPUS_FILES.len());
}

/// Each corpus file's digest must match the manifest.
///
/// Pins the exact bytes, so a substituted or accidentally truncated fixture fails loudly
/// rather than producing a confusing parse error.
#[test]
fn corpus_files_match_their_recorded_digests() {
    let path = corpus_dir().join("manifest.json");
    let text = std::fs::read_to_string(path).expect("manifest must exist");
    let manifest = compitum_json::parse(&text).expect("manifest must be valid JSON");
    let files = manifest["files"]
        .as_object()
        .expect("manifest has a files object");

    assert_eq!(
        files.len(),
        CORPUS_FILES.len(),
        "the manifest and the expected file list have diverged"
    );

    for (name, entry) in files.iter() {
        let bytes = corpus(name);
        let digest = compitum_digest::sha256(&bytes).to_hex();
        assert_eq!(
            digest,
            entry["sha256"].as_str().unwrap_or(""),
            "{name}: the file does not match the digest recorded in the manifest"
        );
        assert_eq!(
            bytes.len() as u64,
            entry["size"].as_u64().unwrap_or(0),
            "{name}: file size disagrees with the manifest"
        );
    }
}

/// The corpus must record which toolchain produced it.
///
/// Without this, a future mismatch is unexplainable: a change in linker behaviour would look
/// like a parser regression.
#[test]
fn manifest_records_its_toolchain() {
    let path = corpus_dir().join("manifest.json");
    let text = std::fs::read_to_string(path).expect("manifest must exist");
    let manifest = compitum_json::parse(&text).expect("valid JSON");

    for tool in ["clang", "lld-link"] {
        let version = manifest["toolchain"][tool].as_str().unwrap_or("");
        assert!(
            !version.is_empty() && version != "unknown",
            "the manifest must name the {tool} version that produced the corpus"
        );
    }
    assert_eq!(
        manifest["generator"].as_str(),
        Some("tools/make_corpus.py"),
        "the manifest must name the script that regenerates it"
    );
}

// ===========================================================================
// The documented ARM64EC limitation.
// ===========================================================================

/// Records the observed behaviour: a linked ARM64EC executable carries machine type `0x8664`.
///
/// clang emits an ARM64EC **object** with machine type `0xA641`
/// (`IMAGE_FILE_MACHINE_ARM64EC`), but lld-link writes an ARM64EC **executable** with machine
/// type `0x8664` (`IMAGE_FILE_MACHINE_AMD64`). The hybrid nature is expressed by the mixture
/// of code and the CHPE metadata, not by the machine field of the linked image.
///
/// This is a genuine limitation of classifying by machine type alone, documented here **with
/// evidence** rather than in prose. It is also why `compitum-pe` reports the CHPE section
/// prefix and the load-configuration directory as additional signals instead of trusting the
/// machine field on its own.
///
/// The routing consequence is asserted in `compitum-router`'s `real_toolchain` test.
#[test]
fn arm64ec_executable_reports_amd64_as_its_machine_type() {
    let image = parse_corpus("real-arm64ec.exe");

    assert_eq!(
        image.coff.machine.raw(),
        0x8664,
        "lld-link writes IMAGE_FILE_MACHINE_AMD64 for a linked ARM64EC executable; if this \
         ever changes, the classification logic and this test must change together"
    );
    assert_eq!(
        image.family().id(),
        "x86_64",
        "by machine type alone this is indistinguishable from a plain x86-64 image, which is \
         exactly the limitation this test documents"
    );
    assert!(
        !image.has_arm64x_slices(),
        "this file carries no CHPE sections either, so the limitation cannot be resolved from \
         the section table"
    );
}

// ===========================================================================
// The machine field must stay authoritative outside the hybrid-capable values.
// ===========================================================================

/// Six distinct architectures must not collapse into one.
///
/// This guards a regression I introduced while adding hybrid detection: `family()` began
/// routing *every* machine value through the CHPE classifier, which knows only three
/// outcomes. As a result I386, Itanium, RISC-V, LoongArch, PowerPC and an unrecognized value
/// all reported as x86-64. Three router tests caught it — a 32-bit x86 image routed to Box64
/// instead of WOW64, and an Itanium image became translatable instead of unsupported.
///
/// The fix was to consult the CHPE metadata only for the four machine values a hybrid image
/// can carry, letting the machine field answer for everything else. This test pins that,
/// because the same mistake is easy to make again: the hybrid classifier is the newer and
/// more interesting code path, and it is tempting to route everything through it.
#[test]
fn every_architecture_is_reported_distinctly() {
    use compitum_pe::fixture::{subsystem, synthetic};

    // (machine value, expected family id) -- from the PE specification.
    let cases: [(u16, &str); 8] = [
        (0xAA64, "arm64"),
        (0x8664, "x86_64"),
        (0x014C, "x86"),
        (0x01C4, "arm32"),
        (0x0200, "ia64"),
        (0x5064, "riscv"),
        (0x6264, "loongarch"),
        (0x01F0, "powerpc"),
    ];

    for (raw, expected) in cases {
        let image = parse(&synthetic(raw, subsystem::CONSOLE, false))
            .unwrap_or_else(|e| panic!("machine 0x{raw:04X} failed to parse: {e}"));
        assert_eq!(
            image.family().id(),
            expected,
            "machine 0x{raw:04X} must report `{expected}`; collapsing architectures together \
             would route them to the wrong backend"
        );
    }
}

/// An unrecognized machine value must not be presented as a known architecture.
#[test]
fn an_unrecognized_machine_stays_unrecognized() {
    use compitum_pe::fixture::{subsystem, synthetic};

    let image = parse(&synthetic(0x1234, subsystem::CONSOLE, false)).expect("parses");
    assert_eq!(
        image.family().id(),
        "other",
        "an unknown machine value must be reported as unknown rather than guessed at"
    );
    assert!(!image.family().is_fully_native_on_arm64());
    assert!(!image.family().needs_full_translation());
}

/// A machine value of zero is not a valid image type.
#[test]
fn a_zero_machine_is_reported_as_unknown() {
    use compitum_pe::fixture::{subsystem, synthetic};

    let image = parse(&synthetic(0x0000, subsystem::CONSOLE, false)).expect("parses");
    assert_eq!(image.family().id(), "unknown");
}

/// The four hybrid-capable machine values are exactly the ones the classifier is consulted for.
///
/// Recorded as a test so the set cannot grow by accident: adding a value here without adding
/// CHPE metadata handling would silently route an architecture through a classifier that does
/// not understand it.
#[test]
fn only_four_machine_values_consult_the_hybrid_classifier() {
    use compitum_pe::fixture::{machine, subsystem, synthetic};

    // ARM64 and AMD64 are the two ABIs ARM64EC and ARM64X combine, plus their two object-file
    // identifiers. Nothing else can carry CHPE metadata.
    let hybrid_capable = [0xAA64u16, 0x8664, 0xA641, 0xA64E];

    for raw in hybrid_capable {
        assert!(
            compitum_pe::Machine(raw).is_arm64_flavour()
                || raw == 0x8664
                || raw == 0xA641
                || raw == 0xA64E
        );
    }

    // Everyone else keeps the answer the machine field alone gives.
    for raw in [0x014Cu16, 0x0200, 0x5064, 0x6264, 0x01F0, 0x01C4] {
        let image = parse(&synthetic(raw, subsystem::CONSOLE, false)).expect("parses");
        assert!(
            !image.is_hybrid(),
            "machine 0x{raw:04X} cannot carry CHPE metadata"
        );
        assert_eq!(
            image.family(),
            compitum_pe::Machine(raw).family(),
            "machine 0x{raw:04X} must be answered by the machine field alone"
        );
    }

    // And the ARM64 case still works end to end.
    let arm64 = parse(&synthetic(machine::ARM64, subsystem::CONSOLE, false)).expect("parses");
    assert_eq!(arm64.family().id(), "arm64");
}
